import { spawn } from 'node:child_process';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const CHROME = 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe';
const PORT = 9507;
const BASE = 'http://127.0.0.1:8798';
const chrome = spawn(CHROME, ['--headless=new', '--disable-gpu', '--no-sandbox', '--hide-scrollbars',
  `--remote-debugging-port=${PORT}`, `--user-data-dir=${mkdtempSync(join(tmpdir(), 'mcz-'))}\\p`, 'about:blank'], { stdio: 'ignore' });
process.on('exit', () => { try { chrome.kill(); } catch {} });
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
let target = null;
for (let i = 0; i < 60 && !target; i++) { await wait(250); try { target = (await fetch(`http://127.0.0.1:${PORT}/json`).then((r) => r.json())).find((t) => t.type === 'page'); } catch {} }
const ws = new WebSocket(target.webSocketDebuggerUrl);
await new Promise((res, rej) => { ws.onopen = res; ws.onerror = rej; });
let id = 0; const pending = new Map();
ws.onmessage = (ev) => { const m = JSON.parse(ev.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m.result); pending.delete(m.id); } };
const send = (method, params = {}) => new Promise((res) => { const i = ++id; pending.set(i, res); ws.send(JSON.stringify({ id: i, method, params })); });
const evl = async (expr) => { const r = await send('Runtime.evaluate', { expression: expr, returnByValue: true, awaitPromise: true }); if (r.exceptionDetails) return 'EVAL: ' + (r.exceptionDetails.exception?.description || 'e').slice(0, 150); return r.result && r.result.value; };
await send('Page.enable'); await send('Runtime.enable');
await send('Page.navigate', { url: BASE + '/admin/' });
await wait(2500);
console.log('href:', await evl('location.href'));
console.log('title:', await evl('document.title'));
console.log('readyState:', await evl('document.readyState'));
console.log('html length:', await evl('(document.documentElement.outerHTML || "").length'));
console.log('shell in DOM:', await evl('document.querySelector("#shell") ? document.querySelector("#shell").outerHTML.length : "null"'));
console.log('body snippet:', JSON.stringify(await evl('(document.body || {innerHTML:"none"}).innerHTML.slice(0, 300)')));
console.log('admin.js status:', (await fetch(BASE + '/admin/admin.js?v=29')).status);
console.log('admin.css status:', (await fetch(BASE + '/admin/admin.css?v=20')).status);
process.exit(0);
